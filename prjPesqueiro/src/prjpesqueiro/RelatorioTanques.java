    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        String pid = txtId.getText();

        if (pid.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Digite o ID do tanque.");
            return;
        }

        int id;
        try {
            id = Integer.parseInt(pid);
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "O ID precisa ser um número.");
            return;
        }

        Tanque tanque = new TanqueDAO().getTanque(id);
        

       if (tanque == null) {
            JOptionPane.showMessageDialog(this, "Tanque não encontrado.");
            return;
        }
       
        EditTanque edit = new EditTanque(tanque);
        edit.setVisible(true);
    }//GEN-LAST:event_btnEditarActionPerformed

