    public void preencheTabela() {
        TanqueDAO tDAO = new TanqueDAO();
        //List<Tanque> listaEspecies = tDAO.getTanques();
        
        List<Tanque> listaTanques = tDAO.getTanquesNome(txtNome.getText());
        DefaultTableModel tabelaTanques = (DefaultTableModel) tblTanques.getModel();
        tabelaTanques.setNumRows(0);
        
        for(Tanque t: listaTanques) {
            Object[] obj = new Object[]{
                t.getId(),
                t.getNome(),
                t.getCapacidade(),
                t.isAtivo()
            }; tabelaTanques.addRow(obj);
        }
    }
    
    
    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        int resposta = JOptionPane.showConfirmDialog(null, "Deseja realmente excluir?", "Exclusão", JOptionPane.YES_NO_OPTION);
        
        if(resposta == JOptionPane.YES_OPTION) {
            TanqueDAO tDAO = new TanqueDAO();
            tDAO.excluir(Integer.parseInt(txtId.getText()));
            txtId.setText("");
            preencheTabela();
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

    
    
    private void btnGerenciarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGerenciarActionPerformed
        String pid = txtId.getText();

        if (pid.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Digite o ID do tanque.");
            return;
        }

        int id;
        try {
            id = Integer.parseInt(pid);
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "O ID precisa ser um número.");
            return;
        }

        Tanque tanque = new TanqueDAO().getTanque(id);
        

        new GerenciarTanque(tanque).setVisible(true);
    }//GEN-LAST:event_btnGerenciarActionPerformed

