    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        String nome = txtNome.getText();
        if (nome.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Digite o nome do tanque.");
            txtNome.requestFocus();
        return;
        }
        if (nome.length() > 30) {
            JOptionPane.showMessageDialog(this, "O nome pode ter no máximo 30 caracteres.");
            return;
        }

        int capacidade;
        try {
            capacidade = Integer.parseInt(txtCapacidade.getText());
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "A capacidade precisa ser um número inteiro.");
            txtCapacidade.requestFocus();
            return;
        }
        if (capacidade <= 0) {
            JOptionPane.showMessageDialog(this, "A capacidade precisa ser maior que zero.");
            return;
        }

        if (!rdoAtivo.isSelected() && !rdoDesativado.isSelected()) {
            JOptionPane.showMessageDialog(this, "Escolha a situação do tanque.");
            return;
        }
        int total = new PeixeTanqueDAO().totalNoTanque(tanque.getId());
        if (capacidade < total) {
            JOptionPane.showMessageDialog(this,
            "O tanque já tem " + total + " peixes. A capacidade não pode ser menor que isso.");
        return;
    }
        
        Tanque t = new Tanque();
        t.setId(tanque.getId());
        t.setNome(txtNome.getText());
        t.setCapacidade(Integer.parseInt(txtCapacidade.getText()));
        t.setAtivo(rdoAtivo.isSelected());

        new TanqueDAO().editar(t);         
        JOptionPane.showMessageDialog(this, "Tanque atualizado!");
        dispose();
    }//GEN-LAST:event_btnSalvarActionPerformed

