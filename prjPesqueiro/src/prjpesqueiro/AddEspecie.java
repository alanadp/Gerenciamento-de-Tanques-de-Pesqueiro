    private List<Especie> especies = new ArrayList<>();

    private void carregarEspecies() {
        List<Especie> lista = new EspecieDAO().getEspecies();
        if (lista != null) {        
            especies = lista;
        }


        for (Especie e : especies) {
            cmbEspecie.addItem(e.getNome());
        }
    }
    
