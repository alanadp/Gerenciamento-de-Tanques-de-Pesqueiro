    private void btnAdicionarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAdicionarActionPerformed
        int indice = cmbEspecie.getSelectedIndex();
        if (indice < 0) {
            JOptionPane.showMessageDialog(this, "Nenhuma espécie cadastrada.");
            return;
        }
        
        int idEspecie = especies.get(indice).getId();

    
        int quantidade;
        try {
            quantidade = Integer.parseInt(txtQuantidade.getText());
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Digite a quantidade (número inteiro).");
            return;
        }
        if (quantidade <= 0) {
            JOptionPane.showMessageDialog(this, "A quantidade precisa ser maior que zero.");
            return;
        }
        
        int total = new PeixeTanqueDAO().totalNoTanque(tanque.getId());
        int livre = tanque.getCapacidade() - total;

        if (quantidade > livre) {
            JOptionPane.showMessageDialog(this,
            "Capacidade excedida! Cabem só mais " + Math.max(livre, 0) + " peixe(s) neste tanque.");
            return;
        }

        int idTanque = tanque.getId();
    
        PeixeTanque pt = new PeixeTanque();
        pt.setIdTanque(idTanque);
        pt.setIdEspecie(idEspecie);
        pt.setQuantidade(quantidade);

        boolean ok = new PeixeTanqueDAO().inserir(pt);

        if (ok) {
            JOptionPane.showMessageDialog(this, "Espécie adicionada ao tanque!");
            dispose();
        } else {
            JOptionPane.showMessageDialog(this, "Não foi possível adicionar. Veja o console.");
        }
    }//GEN-LAST:event_btnAdicionarActionPerformed

