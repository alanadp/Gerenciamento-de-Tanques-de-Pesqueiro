    private int lerIdEspecie() {
        try {
            return Integer.parseInt(txtId.getText());
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Digite o ID da espécie.");
            return 0;
        }
    }
    
    public void preencheTabela() {
        DefaultTableModel tabelaPeixeTanque = (DefaultTableModel) jTable1.getModel();
        tabelaPeixeTanque.setNumRows(0); 

        String filtro = txtNome.getText().toLowerCase();

        
        
        int total = 0;
        for (PeixeTanque p : peixeTanqueDAO.listarPorTanque(tanque.getId())) {
            total += p.getQuantidade();
            if (p.getNomeEspecie().toLowerCase().contains(filtro)) {
                tabelaPeixeTanque.addRow(new Object[]{
                    p.getIdEspecie(), 
                    p.getNomeEspecie(), 
                    p.getQuantidade()
                });
            }
        }

   
        jProgressBar1.setMaximum(Math.max(tanque.getCapacidade(), 1));
        jProgressBar1.setValue(Math.min(total, tanque.getCapacidade()));
        jProgressBar1.setStringPainted(true);
        jProgressBar1.setString(total + " / " + tanque.getCapacidade());
    }
    
    
    
    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        int resposta = JOptionPane.showConfirmDialog(null, "Deseja realmente excluir?", "Exclusão", JOptionPane.YES_NO_OPTION);
        
        if(resposta == JOptionPane.YES_OPTION) {
            PeixeTanqueDAO ptDAO = new PeixeTanqueDAO();
            ptDAO.excluir(Integer.parseInt(txtId.getText()),tanque.getId());
            txtId.setText("");
        }
        
        preencheTabela();
    }//GEN-LAST:event_btnExcluirActionPerformed

