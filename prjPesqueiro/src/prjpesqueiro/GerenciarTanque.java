    private void btnMaisActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMaisActionPerformed
        int idEspecie = lerIdEspecie();
        if (idEspecie < 0) return;

        int total = peixeTanqueDAO.totalNoTanque(tanque.getId());
        if (total + 1 > tanque.getCapacidade()) {
        JOptionPane.showMessageDialog(this, "Tanque cheio! Capacidade: " + tanque.getCapacidade());
        return;}
        
        PeixeTanque pt = new PeixeTanque();
        pt.setIdTanque(tanque.getId());
        pt.setIdEspecie(idEspecie);
        pt.setQuantidade(1);

        peixeTanqueDAO.inserir(pt);
        preencheTabela();
    }//GEN-LAST:event_btnMaisActionPerformed

