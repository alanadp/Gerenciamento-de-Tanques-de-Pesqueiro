    private void btnSituActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSituActionPerformed
        boolean novaSituacao = !tanque.isAtivo();       

        new TanqueDAO().alterarSituacao(tanque.getId(), novaSituacao);
        tanque.setAtivo(novaSituacao);                  

        
        
        atualizarBotaoSituacao();
    }//GEN-LAST:event_btnSituActionPerformed

    private void atualizarBotaoSituacao() {
        boolean ativo = tanque.isAtivo();
        
        btnSitu.setText(tanque.isAtivo() ? "Desativar Tanque" : "Ativar Tanque");
        btnAddEspecie.setEnabled(ativo);   
        btnMais.setEnabled(ativo);     
    }
    
