    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        String nome = txtNome.getText();
        if (nome.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Digite o nome do produto.");
            txtNome.requestFocus();
            return;
        }
        if (nome.length() > 30) {
            JOptionPane.showMessageDialog(this, "O nome pode ter no máximo 30 caracteres.");
            return;
        }

        double preco;
        try {
            preco = Double.parseDouble(txtPreco.getText());
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "O preço precisa ser um número (ex: 12.50).");
            txtPreco.requestFocus();
            return;
        }
        if (preco <= 0) {
            JOptionPane.showMessageDialog(this, "O preço precisa ser maior que zero.");
            return;
        }

        String descricao = txtDescricao.getText();
        if (descricao.length() > 60) {
            JOptionPane.showMessageDialog(this, "A descrição pode ter no máximo 60 caracteres.");
            return;
        }

        Produto p = new Produto();
        p.setId(produto.getId());
        p.setNome(nome);
        p.setPreco(preco);
        p.setDescricao(descricao);

        new ProdutoDAO().editar(p);
        JOptionPane.showMessageDialog(this, "Produto atualizado!");
        dispose(); 
    }//GEN-LAST:event_btnSalvarActionPerformed

