    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        int id;
        try {
            id = Integer.parseInt(txtId.getText());
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Digite o ID da espécie.");
            return;
        }
        Especie especie = new EspecieDAO().getEspecie(id);
        if (especie == null) {
            JOptionPane.showMessageDialog(this, "Espécie não encontrada.");
            return;
        }
        EditEspecie edit = new EditEspecie(especie);

         
        edit.setVisible(true);
    }//GEN-LAST:event_btnEditarActionPerformed

