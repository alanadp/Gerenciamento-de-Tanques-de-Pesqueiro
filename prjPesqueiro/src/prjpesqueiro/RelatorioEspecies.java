    public void preencheTabela() {
        EspecieDAO eDAO = new EspecieDAO();
        //List<Especie> listaEspecies = eDAO.getEspecies();
        
        List<Especie> listaEspecies = eDAO.getEspeciesNome(txtNome.getText());
        DefaultTableModel tabelaEspecies = (DefaultTableModel) tblEspecies.getModel();
        tabelaEspecies.setNumRows(0); 
        
        for(Especie e: listaEspecies) {
            Object[] obj = new Object[]{
                e.getId(),
                e.getNome(),
                e.getPrecoKg(),
                e.getDescricao()
            }; tabelaEspecies.addRow(obj);
        }
    }

